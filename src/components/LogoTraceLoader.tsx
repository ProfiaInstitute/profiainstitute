const OUTLINE_DURATION_MS = 700;

function positiveDuration(value: number, fallback: number) {
  return Number.isFinite(value) && value >= 0 ? value : fallback;
}

export function LogoTraceLoader({
  loading = true,
  isComplete = false,
  size = 160,
  strokeWidth = 2,
  loopDurationSeconds = 1.8,
  fillFadeSeconds = 0.35,
  className,
  ariaLabel = "Loading",
  onDone,
}: LogoTraceLoaderProps) {
  const [phase, setPhase] = useState<LoaderPhase>("loop");
  const [reducedMotion, setReducedMotion] = useState(false);
  const onDoneRef = useRef(onDone);
  const doneCalledRef = useRef(false);
  const shouldFinish = isComplete || !loading;
  const safeLoopDuration = positiveDuration(loopDurationSeconds, 1.8);
  const safeFillFadeDuration = positiveDuration(fillFadeSeconds, 0.35);

  useEffect(() => {
    onDoneRef.current = onDone;
  }, [onDone]);

  useEffect(() => {
    if (typeof window.matchMedia !== "function") return;
    const mediaQuery = window.matchMedia("(prefers-reduced-motion: reduce)");
    const updateReducedMotion = () => setReducedMotion(mediaQuery.matches);
    updateReducedMotion();
    mediaQuery.addEventListener("change", updateReducedMotion);
    return () => mediaQuery.removeEventListener("change", updateReducedMotion);
  }, []);

  useEffect(() => {
    if (reducedMotion) {
      setPhase("done");
    } else if (shouldFinish && phase === "loop") {
      setPhase("closingOutline");
    }
  }, [phase, reducedMotion, shouldFinish]);

  useEffect(() => {
    if (phase !== "closingOutline") return;
    const timeout = window.setTimeout(() => setPhase("fadingFill"), OUTLINE_DURATION_MS);
    return () => window.clearTimeout(timeout);
  }, [phase]);

  useEffect(() => {
    if (phase !== "fadingFill") return;
    const timeout = window.setTimeout(() => setPhase("done"), safeFillFadeDuration * 1000);
    return () => window.clearTimeout(timeout);
  }, [phase, safeFillFadeDuration]);

  useEffect(() => {
    if (phase !== "done" || doneCalledRef.current) return;
    doneCalledRef.current = true;
    onDoneRef.current?.();
  }, [phase]);

  const phaseClass = `logo-trace-loader--${phase}`;

  return (
    <svg
      role="status"
      aria-label={ariaLabel}
      viewBox={LOGO_VIEW_BOX}
      width={size}
      height={size}
      className={["logo-trace-loader", phaseClass, className].filter(Boolean).join(" ")}
      style={{ "--logo-fill-fade-duration": `${safeFillFadeDuration}s` } as CSSProperties}
    >
      <path
        className="logo-trace-loader__ghost"
        d={TRACE_PATH}
        fill="none"
        stroke="currentColor"
        strokeWidth={Math.max(1, strokeWidth / 2)}
        strokeLinejoin="round"
        pathLength={1}
      />
      {phase === "loop" ? (
        <path
          className="logo-trace-loader__loop"
          d={TRACE_PATH}
          fill="none"
          stroke="currentColor"
          strokeWidth={strokeWidth}
          strokeLinecap="round"
          strokeLinejoin="round"
          pathLength={1}
          strokeDasharray="0.16 0.84"
          style={{ animationDuration: `${safeLoopDuration}s` }}
        />
      ) : null}
      {phase === "closingOutline" ? (
        <path
          className="logo-trace-loader__closing"
          d={TRACE_PATH}
          fill="none"
          stroke="currentColor"
          strokeWidth={strokeWidth}
          strokeLinecap="round"
          strokeLinejoin="round"
          pathLength={1}
        />
      ) : null}
      <image
        className="logo-trace-loader__fills"
        href={LOGO_IMAGE}
        x="0"
        y="0"
        width="223"
        height="226"
        aria-hidden="true"
      />
    </svg>
  );
}
